#!/usr/bin/env python3
"""Regenerate the Odin #load table for runtime game assets."""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MAIN = (ROOT / "main.odin").read_text()
AUDIO = (ROOT / "game_audio.odin").read_text()

png_paths = set(re.findall(r'"([^\"]+\.png)"', MAIN))
png_paths.update(("assets/textures/stone_texture.png", "assets/textures/wood_texture.png"))
shader_paths = ("assets/shaders/intro_slowmo.fs", "assets/shaders/intro_slowmo_web.fs")
names_block = AUDIO.split("SFX_NAMES :=", 1)[1].split("}", 1)[0]
sound_names = re.findall(r'"([^\"]+)"', names_block)
sound_paths = [f"assets/sfx/{name}_{variant:02d}.wav"
               for name in sound_names for variant in range(1, 4)]
paths = sorted(png_paths | set(shader_paths) | set(sound_paths))
for path in paths:
    if not (ROOT / path).is_file():
        raise SystemExit(f"Missing runtime asset: {path}")

lines = [
    "package main",
    "",
    '// Generated by tools/generate_embedded_assets.py; rerun after changing runtime assets.',
    'import "core:c"',
    'import rl "vendor:raylib"',
    "",
    "embedded_asset :: proc(path: string) -> []u8 {",
    "    switch path {",
]
for path in paths:
    lines.append(f'    case "{path}": return #load("{path}")')
lines += [
    "    }",
    "    return nil",
    "}",
    "",
    "load_embedded_image :: proc(path: string) -> rl.Image {",
    "    data := embedded_asset(path)",
    "    if len(data) == 0 { return {} }",
    '    return rl.LoadImageFromMemory(".png", raw_data(data), c.int(len(data)))',
    "}",
    "",
    "load_embedded_texture :: proc(path: string) -> rl.Texture2D {",
    "    image := load_embedded_image(path)",
    "    if !rl.IsImageValid(image) { return {} }",
    "    defer rl.UnloadImage(image)",
    "    return rl.LoadTextureFromImage(image)",
    "}",
    "",
    "load_embedded_sound :: proc(path: string) -> rl.Sound {",
    "    data := embedded_asset(path)",
    "    if len(data) == 0 { return {} }",
    '    wave := rl.LoadWaveFromMemory(".wav", raw_data(data), c.int(len(data)))',
    "    if !rl.IsWaveValid(wave) { return {} }",
    "    defer rl.UnloadWave(wave)",
    "    return rl.LoadSoundFromWave(wave)",
    "}",
    "",
    "load_embedded_shader :: proc(path: string) -> rl.Shader {",
    "    data := embedded_asset(path)",
    "    if len(data) == 0 { return {} }",
    "    source := make([]u8, len(data)+1)",
    "    defer delete(source)",
    "    copy(source, data)",
    "    return rl.LoadShaderFromMemory(nil, cstring(raw_data(source)))",
    "}",
    "",
]
destination = ROOT / "embedded_assets.odin"
destination.write_text("\n".join(lines))
print(f"{destination}: {len(png_paths)} PNG, {len(shader_paths)} shaders, {len(sound_paths)} WAV")
